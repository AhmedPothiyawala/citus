import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

async function runSanityCheck() {
  console.log('===========================================================');
  console.log('   CITIUSCOMM — FULL AUTOMATED SANITY & ASSET AUDIT');
  console.log('===========================================================');

  let passed = true;
  let errors: string[] = [];

  // 1. Check all image assets exist and are non-empty
  const imagesDir = path.join(ROOT, 'public', 'images');
  if (!fs.existsSync(imagesDir)) {
    errors.push('public/images directory does not exist');
  } else {
    const images = fs.readdirSync(imagesDir).filter((f) => !f.startsWith('.'));
    console.log(`[PASS] Found ${images.length} HD image assets in public/images/`);

    let zeroByteCount = 0;
    for (const img of images) {
      const stats = fs.statSync(path.join(imagesDir, img));
      if (stats.size === 0) {
        zeroByteCount++;
        errors.push(`Empty image file: ${img}`);
      }
    }
    if (zeroByteCount === 0) {
      console.log(`[PASS] All ${images.length} images are valid non-empty files.`);
    }
  }

  // 2. Check all 19 page files exist
  const pagesDir = path.join(ROOT, 'src', 'pages');
  const expectedPages = [
    'HomePage.tsx',
    'CompanyProfilePage.tsx',
    'WhyUsPage.tsx',
    'LeadershipPage.tsx',
    'PartnersPage.tsx',
    'ProductsPage.tsx',
    'DigitalServicesPage.tsx',
    'NetworkingPage.tsx',
    'FttxPage.tsx',
    'ServerStoragePage.tsx',
    'DataCenterCloudPage.tsx',
    'IndustryApplicationsPage.tsx',
    'SecuritySolutionsPage.tsx',
    'CaseStudiesPage.tsx',
    'RakutenMobilePage.tsx',
    'NepalTelecomPage.tsx',
    'NetBroadbandPage.tsx',
    'CareersPage.tsx',
    'ContactPage.tsx',
  ];

  for (const page of expectedPages) {
    const filePath = path.join(pagesDir, page);
    if (!fs.existsSync(filePath)) {
      errors.push(`Missing page component: ${page}`);
    } else {
      const content = fs.readFileSync(filePath, 'utf-8');
      if (!content.includes('export const') && !content.includes('export function')) {
        errors.push(`Page component ${page} has no exported component`);
      }
    }
  }
  console.log(`[PASS] All ${expectedPages.length} page components exist and export valid React components.`);

  // 3. Verify single source of truth (site.ts)
  const siteTsPath = path.join(ROOT, 'src', 'data', 'site.ts');
  if (!fs.existsSync(siteTsPath)) {
    errors.push('src/data/site.ts does not exist');
  } else {
    const content = fs.readFileSync(siteTsPath, 'utf-8');
    const requiredExports = [
      'LINKS',
      'COMPANY_INFO',
      'MAIN_NAV',
      'LEADERSHIP_TEAM',
      'PARTNERS_LIST',
      'CLIENTS_LIST',
      'CASE_STUDIES',
      'CAREER_OPENINGS',
      'OFFICES_LIST',
    ];
    for (const exp of requiredExports) {
      if (!content.includes(`export const ${exp}`) && !content.includes(`export let ${exp}`)) {
        errors.push(`Missing export in site.ts: ${exp}`);
      }
    }
    console.log(`[PASS] Single source of truth (site.ts) exports all ${requiredExports.length} datasets.`);
  }

  // 4. Verify distribution bundle
  const distHtml = path.join(ROOT, 'dist', 'index.html');
  if (fs.existsSync(distHtml)) {
    console.log('[PASS] Production dist bundle is present and built.');
  } else {
    console.log('[INFO] Production dist bundle not built yet (will be generated by npm run build).');
  }

  console.log('-----------------------------------------------------------');
  if (errors.length > 0) {
    console.error(`[FAIL] Sanity check failed with ${errors.length} error(s):`);
    errors.forEach((e) => console.error(`  - ${e}`));
    process.exit(1);
  } else {
    console.log('[SUCCESS] All sanity checks passed cleanly!');
    console.log('===========================================================');
  }
}

runSanityCheck();
